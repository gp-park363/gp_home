@dataclass(frozen=True)
class Location:
    key: str
    name: str
    summary: str
    address: str
    tel: str
    transit: str

    @property
    def map_url(self) -> str:
        from urllib.parse import quote

        return f"https://map.naver.com/p/search/{quote(self.address)}"


